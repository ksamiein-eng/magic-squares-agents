"""Rebuild the eight supplied rank-one finite-field sieves, without PARI.
This is a congruence computation on the subgroup generated by the recorded point.
It does not establish that this subgroup is the full Mordell-Weil group.
"""
from pathlib import Path
from math import gcd,isqrt,lcm
from fractions import Fraction
from concurrent.futures import ProcessPoolExecutor
import json,ast,sys,time
from collections import Counter

def primes(N):
 b=bytearray(b'\x01')*N;b[0:2]=b'\x00\x00'
 for n in range(2,isqrt(N)+1):
  if b[n]: b[n*n:N:n]=b'\x00'*len(b[n*n:N:n])
 return [i for i in range(3,N) if b[i]]

def disc(a):
 _,b,_,c,d=a
 return -64*c**3-16*b*b*(4*b*d-c*c)-432*d*d+288*b*c*d

def add(P,Q,a,p):
 if P is None:return Q
 if Q is None:return P
 x,y=P;u,v=Q
 if x==u:
  if (y+v)%p==0:return None
  z=(3*x*x+2*a[1]*x+a[3])*pow(2*y,-1,p)%p
 else:z=(v-y)*pow(u-x,-1,p)%p
 X=(z*z-a[1]-x-u)%p
 return X,(z*(x-X)-y)%p

def intersect(R,M,S,N):
 g=gcd(M,N);step=N//g;L=M*step
 if step==1:return {r for r in R if r%N in S},M
 buckets={}
 for s in S:buckets.setdefault(s%g,[]).append(s)
 inv=pow(M//g,-1,step)
 return {r+M*(((s-r)//g*inv)%step) for r in R for s in buckets.get(r%g,[])},L

def one(payload):
 name,r=payload;start=time.time();a=r['weierstrass_a_invariants'];M=r['modulus_M'][0]
 A=int(r['f'].split()[0]);G=tuple(ast.literal_eval(r['generator_XY'][0])); delta=disc(a)
 assert G[1]**2==G[0]**3+a[1]*G[0]**2+a[3]*G[0]+a[4]
 constraints=[]
 for p in primes(4000):
  if delta%p==0 or A%p==0:continue
  gp=tuple(x%p for x in G);P=None;allowed=set();invA=pow(A,-1,p)
  for k in range(p+2+2*isqrt(p)+2):
   if P is None or pow(P[0]*invA%p,(p-1)//2,p) in (0,1):allowed.add(k)
   P=add(P,gp,a,p)
   if P is None:break
  else:raise RuntimeError('order computation failed')
  order=k+1
  if M%order==0:constraints.append({'prime':p,'order':order,'allowed':sorted(allowed)})
 constraints.sort(key=lambda r:(r['order'],len(r['allowed']),r['prime']))
 residues={0};mod=1;steps=[];peak=1
 todo=list(constraints)
 while todo:
  def score(con):
   g=gcd(mod,con['order']); ar=Counter(x%g for x in residues); br=Counter(x%g for x in con['allowed'])
   size=sum(n*br.get(k,0) for k,n in ar.items())
   return (size,lcm(mod,con['order']),con['prime'])
  con=min(todo,key=score);todo.remove(con)
  residues,mod=intersect(residues,mod,set(con['allowed']),con['order']);peak=max(peak,len(residues))
  steps.append({'prime':con['prime'],'order':con['order'],'modulus':mod,'survivor_count':len(residues)})
  if len(residues)>2000000:raise RuntimeError('sieve size safeguard')
 assert mod==M,(name,mod,M)
 claimed={p[0]%M for p in r['survivors_signed']}
 signed=sorted(x if x<=M//2 else x-M for x in residues)
 record={'name':name,'M':M,'prime_count':len(constraints),'matches_uploaded':residues==claimed,'computed_survivors':signed,'claimed_survivors':sorted(x[0] for x in r['survivors_signed']),'extra_computed':sorted(residues-claimed),'missing_computed':sorted(claimed-residues),'max_intermediate_classes':peak,'constraints':constraints,'steps':steps,'runtime_s':round(time.time()-start,3)}
 print(name,'primes',len(constraints),'match',record['matches_uploaded'],'survivors',signed,'time',record['runtime_s'],flush=True)
 return record

def main(root,out):
 d=json.load(open(root/'chabauty_inputs/sieves_cubic.json'))
 jobs=[(n,r) for n,r in d['curves'].items() if 'weierstrass_a_invariants' in r]
 with ProcessPoolExecutor(max_workers=4) as pool:rows=list(pool.map(one,jobs))
 out.write_text(json.dumps({'scope':'Rank-one subgroup congruences only; rank, basis saturation, canonical-height bounds and orbit-to-curve maps not certified.', 'all_match':all(r['matches_uploaded'] for r in rows),'rows':rows},indent=2))
if __name__=='__main__':main(Path(sys.argv[1]),Path(sys.argv[2]))
